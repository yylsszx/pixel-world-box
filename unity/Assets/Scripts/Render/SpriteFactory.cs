        private static void Human(string key, Color32 skin, Color32 cloth, Color32 hair, Color32 pants, St st = St.None)
        {
            var px = new Px(8, 12);
            Color32 dark = Shade(cloth, -35);

            // 双腿(法师袍遮盖)
            if ((st & St.Robe) != 0)
            {
                px.R(2, 1, 4, 6, cloth);
                px.R(1, 1, 6, 1, cloth);
                px.R(2, 1, 4, 1, dark);
            }
            else
            {
                px.R(2, 1, 1, 3, pants);
                px.R(5, 1, 1, 3, pants);
                px.P(2, 0, Shade(pants, -40));
                px.P(5, 0, Shade(pants, -40));
            }

            // 躯干 + 腰带 + 双臂
            px.R(2, 4, 4, 4, cloth);
            px.R(2, 4, 4, 1, dark);
            px.R(1, 5, 1, 3, skin);
            px.R(6, 5, 1, 3, skin);

            // 头(肤色 4×3)+双眼+发
