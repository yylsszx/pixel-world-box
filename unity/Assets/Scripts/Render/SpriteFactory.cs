        private static void Fx()
        {
            {   // 1×1 白点
                var px = new Px(1, 1);
                px.P(0, 0, C(255, 255, 255));
                px.Bake("fx_dot");
            }
            {   // 16×16 白环
                var px = new Px(16, 16);
                for (int y = 0; y < 16; y++)
                    for (int x = 0; x < 16; x++)
                    {
                        float dx = x - 7.5f, dy = y - 7.5f;
                        float d = Mathf.Sqrt(dx * dx + dy * dy);
                        if (d > 6.1f && d < 7.5f) px.P(x, y, C(255, 255, 255));
                    }
                px.Bake("fx_ring");
            }
            {   // 闪电竖折线 8×16
                var px = new Px(8, 16);
                int[] cx = { 4, 4, 4, 2, 2, 2, 5, 5, 5, 3, 3, 3, 6, 6, 6, 6 };
                for (int y = 0; y < 16; y++)
                {
                    int x = cx[15 - y];
                    px.P(x, y, C(235, 245, 255));
                    px.P(x + 1, y, C(235, 245, 255));
                    px.P(x - 1, y, C(150, 190, 255));
                    px.P(x + 2, y, C(150, 190, 255));
                }
                px.Bake("fx_bolt");
            }
            {   // 十字光 5×5
                var px = new Px(5, 5);
                px.R(2, 0, 1, 5, C(255, 255, 255));
                px.R(0, 2, 5, 1, C(255, 255, 255));
                px.Bake("fx_cross");
            }
        }
