            Color32 eye = (st & St.RedEyes) != 0 ? C(215, 55, 40) : C(32, 28, 24);
            px.P(3, 9, eye);
            px.P(5, 9, eye);
            px.R(2, 11, 4, 1, hair);
            px.P(2, 10, hair);
            px.P(5, 10, hair);

            // 种族特征
            if ((st & St.Ears) != 0) { px.P(1, 9, skin); px.P(6, 9, skin); }                    // 精灵尖耳
            if ((st & St.GoblinEars) != 0) { px.R(0, 10, 2, 1, skin); px.R(6, 10, 2, 1, skin); } // 哥布林大耳
            if ((st & St.Helm) != 0) { px.R(2, 10, 4, 2, C(168, 174, 186)); px.P(2, 9, C(146, 152, 165)); } // 矮人钢盔
            if ((st & St.Beard) != 0)                                                            // 矮人白须
            {
                px.R(2, 6, 4, 2, C(236, 236, 232));
                px.P(1, 6, C(236, 236, 232));
                px.P(6, 6, C(236, 236, 232));
            }
            if ((st & St.Tusks) != 0) { px.P(2, 8, C(242, 240, 228)); px.P(5, 8, C(242, 240, 228)); } // 兽人獠牙
            if ((st & St.Bandana) != 0) { px.R(2, 10, 4, 2, C(122, 32, 32)); px.P(6, 11, C(122, 32, 32)); } // 强盗头巾
            if ((st & St.Rot) != 0) { px.P(2, 7, C(96, 110, 78)); px.P(5, 5, C(96, 110, 78)); px.P(4, 8, C(112, 126, 92)); } // 僵尸腐斑
