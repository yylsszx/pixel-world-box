        private static Color32 C(int r, int g, int b, int a = 255)
        {
            return new Color32((byte)r, (byte)g, (byte)b, (byte)a);
        }

        private static Color32 Shade(Color32 c, int d)
        {
            int r = c.r + d, g = c.g + d, b = c.b + d;
            if (r < 0) r = 0; if (r > 255) r = 255;
            if (g < 0) g = 0; if (g > 255) g = 255;
            if (b < 0) b = 0; if (b > 255) b = 255;
            return new Color32((byte)r, (byte)g, (byte)b, c.a);
        }

        private sealed class Px
        {
            public readonly int W, H;
            private readonly Color32[] _buf;
            public Px(int w, int h) { W = w; H = h; _buf = new Color32[w * h]; }
            public void P(int x, int y, Color32 c)
            {
                if (x >= 0 && y >= 0 && x < W && y < H) _buf[y * W + x] = c;
            }
            public void R(int x, int y, int w, int h, Color32 c)
            {
                for (int j = y; j < y + h; j++)
                    for (int i = x; i < x + w; i++)
                        P(i, j, c);
            }
            public void Bake(string key)
            {
                var tex = new Texture2D(W, H, TextureFormat.RGBA32, false);
                tex.filterMode = FilterMode.Point;
                tex.wrapMode = TextureWrapMode.Clamp;
                tex.SetPixels32(_buf);
                tex.Apply(false, false);
                S[key] = Sprite.Create(tex, new Rect(0f, 0f, W, H), new Vector2(0.5f, 0.5f), 16f);
            }
        }

